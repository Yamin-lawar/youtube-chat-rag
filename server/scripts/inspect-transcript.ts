// RAG block 1: look at the raw transcript before doing anything with it.
//   npx tsx scripts/inspect-transcript.ts <youtube-id>
import { YoutubeTranscriptProvider } from '../src/rag/transcript/youtubeProvider.js';

const youtubeId = process.argv[2] ?? 'JljlsOJmlCA';

const transcript = await new YoutubeTranscriptProvider().getTranscript(youtubeId);
const { segments } = transcript;

const fullText = segments.map((segment) => segment.text).join(' ');
const lastSegment = segments[segments.length - 1];
const videoLengthMin = lastSegment ? (lastSegment.startMs + lastSegment.durationMs) / 60000 : 0;

function formatTime(ms: number): string {
  const totalSeconds = Math.floor(ms / 1000);
  const minutes = Math.floor(totalSeconds / 60);
  const seconds = String(totalSeconds % 60).padStart(2, '0');
  return `${minutes}:${seconds}`;
}

console.log(
  'language:       ',
  transcript.language,
  transcript.isAutoGenerated ? '(auto-generated)' : '',
);
console.log('segments:       ', segments.length);
console.log('characters:     ', fullText.length);
console.log('words:          ', fullText.split(/\s+/).length);
console.log('video length:   ', videoLengthMin.toFixed(1), 'min');
console.log('avg segment:    ', Math.round(fullText.length / segments.length), 'chars');

console.log('\nFirst 8 segments:');
for (const segment of segments.slice(0, 8)) {
  console.log(`  [${formatTime(segment.startMs)}] ${segment.text}`);
}

console.log('\nLast 3 segments:');
for (const segment of segments.slice(-3)) {
  console.log(`  [${formatTime(segment.startMs)}] ${segment.text}`);
}

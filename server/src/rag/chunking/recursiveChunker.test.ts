import { describe, expect, it } from 'vitest';
import type { Transcript } from '../transcript/types.js';
import { RecursiveChunker } from './recursiveChunker.js';

// Ten segments of 10 seconds each, e.g. "word0 word0 word0 ...".
function makeTranscript(segmentCount: number): Transcript {
  return {
    youtubeId: 'test',
    language: 'en',
    isAutoGenerated: false,
    segments: Array.from({ length: segmentCount }, (_, i) => ({
      text: `segment${i} `.repeat(5).trim(),
      startMs: i * 10_000,
      durationMs: 10_000,
    })),
  };
}

describe('RecursiveChunker', () => {
  it('keeps a short transcript in a single chunk covering the whole video', async () => {
    const chunks = await new RecursiveChunker({ chunkSize: 1000, chunkOverlap: 100 }).chunk(
      makeTranscript(3),
    );

    expect(chunks).toHaveLength(1);
    expect(chunks[0]).toMatchObject({ index: 0, startMs: 0, endMs: 30_000 });
  });

  it('splits long transcripts into chunks no larger than chunkSize', async () => {
    const chunks = await new RecursiveChunker({ chunkSize: 200, chunkOverlap: 40 }).chunk(
      makeTranscript(30),
    );

    expect(chunks.length).toBeGreaterThan(1);
    for (const chunk of chunks) {
      expect(chunk.text.length).toBeLessThanOrEqual(200);
    }
  });

  it('gives chunks increasing timestamps within the video bounds', async () => {
    const chunks = await new RecursiveChunker({ chunkSize: 200, chunkOverlap: 40 }).chunk(
      makeTranscript(30),
    );

    for (let i = 1; i < chunks.length; i++) {
      expect(chunks[i]!.startMs).toBeGreaterThanOrEqual(chunks[i - 1]!.startMs);
    }
    expect(chunks[0]!.startMs).toBe(0);
    expect(chunks.at(-1)!.endMs).toBe(300_000);
  });

  it('maps a chunk to the segments whose text it contains', async () => {
    const chunks = await new RecursiveChunker({ chunkSize: 200, chunkOverlap: 40 }).chunk(
      makeTranscript(30),
    );

    // The first word of a chunk comes from the segment where the chunk starts.
    const chunk = chunks[2]!;
    const firstSegmentNumber = Number(/segment(\d+)/.exec(chunk.text)![1]);
    expect(chunk.startMs).toBeLessThanOrEqual(firstSegmentNumber * 10_000);
    expect(chunk.startMs + 10_000).toBeGreaterThan(firstSegmentNumber * 10_000);
  });

  it('overlaps neighbouring chunks', async () => {
    const chunks = await new RecursiveChunker({ chunkSize: 200, chunkOverlap: 60 }).chunk(
      makeTranscript(30),
    );

    expect(chunks[1]!.startMs).toBeLessThan(chunks[0]!.endMs);
  });
});

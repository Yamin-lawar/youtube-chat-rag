import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { CachingTranscriptProvider } from './cachingTranscriptProvider.js';
import type { Transcript, TranscriptProvider } from './types.js';

const transcript: Transcript = {
  youtubeId: 'abc_123-X',
  language: 'en',
  isAutoGenerated: true,
  segments: [{ text: 'hello there', startMs: 0, durationMs: 2000 }],
};

describe('CachingTranscriptProvider', () => {
  let directory: string;
  beforeEach(async () => {
    directory = await mkdtemp(join(tmpdir(), 'transcripts-'));
  });
  afterEach(async () => {
    await rm(directory, { recursive: true, force: true });
  });

  function innerProvider() {
    const getTranscript = vi.fn(async () => transcript);
    const inner: TranscriptProvider = { getTranscript };
    return { inner, getTranscript };
  }

  it('downloads a video once and reads it from the file after that', async () => {
    const { inner, getTranscript } = innerProvider();
    const provider = new CachingTranscriptProvider(inner, directory);

    expect(await provider.getTranscript('abc_123-X')).toEqual(transcript);
    // A new instance has no memory, so this read must come from the file.
    expect(
      await new CachingTranscriptProvider(inner, directory).getTranscript('abc_123-X'),
    ).toEqual(transcript);
    expect(getTranscript).toHaveBeenCalledTimes(1);
  });

  it('does not store a failed download', async () => {
    const getTranscript = vi
      .fn<TranscriptProvider['getTranscript']>()
      .mockRejectedValueOnce(new Error('no captions'))
      .mockResolvedValueOnce(transcript);
    const provider = new CachingTranscriptProvider({ getTranscript }, directory);

    await expect(provider.getTranscript('abc_123-X')).rejects.toThrow('no captions');
    expect(await provider.getTranscript('abc_123-X')).toEqual(transcript);
  });

  it('refuses an id that could point outside the folder', async () => {
    const { inner } = innerProvider();
    await expect(
      new CachingTranscriptProvider(inner, directory).getTranscript('../secret'),
    ).rejects.toThrow('Not a YouTube video id');
  });
});

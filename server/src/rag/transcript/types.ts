/** One caption line with its position in the video. */
export interface TranscriptSegment {
  text: string;
  startMs: number;
  durationMs: number;
}

export interface Transcript {
  youtubeId: string;
  language: string;
  /** True when YouTube generated the captions automatically (speech recognition). */
  isAutoGenerated: boolean;
  segments: TranscriptSegment[];
}

/**
 * Anything that can turn a YouTube video id into a transcript. Keeping this as an
 * interface means a fallback provider can replace the YouTube one without
 * touching the rest of the pipeline.
 */
export interface TranscriptProvider {
  getTranscript(youtubeId: string): Promise<Transcript>;
}

/** Thrown when a video has no usable captions or YouTube refuses the request. */
export class TranscriptUnavailableError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'TranscriptUnavailableError';
  }
}
